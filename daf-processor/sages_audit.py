#!/usr/bin/env python3
"""Checks the sages kit's relationships for links that can't be right, for the author's review.
No API calls.

    venv/bin/python sages_audit.py      # -> outline/sages/audit.md

A link is flagged when the generations make it impossible or unlikely (a teacher two or more
generations after his student, a father after his son, a tanna who is an amora's student), or
when one person stands in two family relations to the same sage. Each flag names where the link
came from (sefaria / wikipedia), since the fix differs: Sefaria's links are dropped in
kit_overrides.json, a Wikipedia misreading may be a parser bug.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
KIT = HERE.parent / "AnyMishnahWeb" / "reference-kit" / "sages" / "sages.json"
OUT = HERE / "outline" / "sages" / "audit.md"


def era(x):
    """One scale for all: Zugot -4..0, tanna'im 1-6, the transition 6.5, amora'im 7-14."""
    c = (x.get("gen_code") or "").split("/")[0]
    if not c and x.get("gen") is not None:
        c = {"tanna": "T", "amora": "A", "zug": "Z"}.get(x["kind"], "?") + str(x["gen"])
    if c == "TA" or c == "T0":
        return 6.5
    try:
        n = int(c[1:])
    except ValueError:
        return None
    return {"Z": n - 5, "T": n, "A": n + 6}.get(c[0])


def main():
    S = json.loads(KIT.read_text(encoding="utf-8"))["sages"]
    flags = []
    def flag(kind, a, rel, b, why, by):
        flags.append((kind, a, rel, b, why, by))
    seen = set()
    for a, x in S.items():
        ea = era(x)
        for rel, items in x["links"].items():
            for it in items:
                b = it.get("id")
                if not b or b not in S:
                    continue
                y, eb = S[b], era(S[b])
                by = "/".join(it.get("by", []))
                key = tuple(sorted((a, b))) + (rel,)
                if ea is None or eb is None:
                    continue
                d = eb - ea                      # how many generations b comes after a
                if rel == "teachers" and (a, b) not in seen:
                    seen.add((a, b))
                    if d >= 1:
                        flag("order", a, "teacher", b, f"teacher {d:g} generation(s) after the student", by)
                    elif d <= -4:
                        flag("gap", a, "teacher", b, f"teacher {-d:g} generations before the student", by)
                    if x["kind"] == "tanna" and y["kind"] == "amora":
                        flag("kind", a, "teacher", b, "an amora as a tanna's teacher", by)
                if rel in ("father", "mother", "parents") and d >= 1:
                    flag("order", a, rel, b, f"parent {d:g} generation(s) after the child", by)
                if rel in ("father", "mother", "parents") and d <= -3:
                    flag("gap", a, rel, b, f"parent {-d:g} generations before the child", by)
                if rel == "grandparents" and d >= 0:
                    flag("order", a, rel, b, "grandparent not before the grandchild", by)
                if rel == "colleagues" and abs(d) >= 3 and key not in seen:
                    seen.add(key)
                    flag("gap", a, "colleague", b, f"colleagues {abs(d):g} generations apart", by)
        # one person in two family relations to the same sage
        fam = {}
        for rel in ("father", "mother", "parents", "children", "spouse", "in_laws", "sons_in_law",
                    "siblings", "grandchildren", "grandparents"):
            for it in x["links"].get(rel, []):
                if it.get("id"):
                    fam.setdefault(it["id"], []).append((rel, bool(it.get("notes"))))
        for b, rs in fam.items():
            if len(rs) > 1:
                flag("two-way", a, "+".join(r for r, _ in rs), b,
                     "listed in two family relations" + (" (one with a note)" if any(n for _, n in rs) else ""),
                     "")
    name = lambda k: S[k]["en"]
    order = {"order": 0, "kind": 1, "two-way": 2, "gap": 3}
    flags.sort(key=lambda f: (order[f[0]], name(f[1])))
    lines = ["# Sages: relationship audit (generated by daf-processor/sages_audit.py)", "",
             f"{len(flags)} flags. **order**: impossible by generation (likely wrong). **kind**: an amora "
             "teaching a tanna. **two-way**: one person in two family relations. **gap**: unlikely "
             "(teachers four or more generations earlier, colleagues three or more apart): often a "
             "real link with a wrong generation on one side.", "",
             "Fix: `drop_links` / `add_links` in `outline/sages/kit_overrides.json`, or a generation "
             "fix in `outline/sages/overrides.json`.", ""]
    for kind in order:
        rows = [f for f in flags if f[0] == kind]
        if not rows:
            continue
        lines += [f"## {kind} ({len(rows)})", "", "| Sage | relation | Other | Why | From |", "|---|---|---|---|---|"]
        for _, a, rel, b, why, by in rows:
            lines.append(f"| {name(a)} ({S[a].get('gen_code') or '?'}) | {rel} | {name(b)} ({S[b].get('gen_code') or '?'}) | {why} | {by} |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    from collections import Counter
    print(Counter(f[0] for f in flags), Counter(f[5] for f in flags if f[0] != "two-way"), "->", OUT)


if __name__ == "__main__":
    main()
