#!/usr/bin/env python3
"""Family links that Hebrew Wikipedia states in an article's TEXT but not in its infobox.
sages_wiki.py reads only the infobox (תבנית:אישיות רבנית), so a father who is named only in the prose
("אביו, [[רבן שמעון בן גמליאל הזקן]]") is never recorded. This scans the prose of every cached page for
a family word followed by a link, resolves the link to a sage the way sages_wiki.py does, and lists the
relations sages.json does not have yet. It writes nothing but the report:

    venv/bin/python sages_body_audit.py        # -> outline/sages/body_relations_audit.md

Each line is a CANDIDATE for the author to check against the article; accepted ones go into
kit_overrides.json add_links. Facts only, never Wikipedia's wording."""
import json, re
from build_sages import CACHE, OUT
PAGES = CACHE / "hewiki_pages"
sages = json.loads((OUT / "sages.json").read_text(encoding="utf-8"))
KIT = OUT.parents[2] / "AnyMishnahWeb/reference-kit/sages/sages.json"   # the generated kit data: every link already recorded, by any source
kit = json.loads(KIT.read_text(encoding="utf-8"))["sages"]
canon = json.loads((CACHE / "hewiki_canonical.json").read_text(encoding="utf-8"))
page_of = {}
for f in PAGES.glob("*.json"):
    d = json.loads(f.read_text(encoding="utf-8"))
    if d.get("title"): page_of.setdefault(d["title"], []).append(f.stem)
owner = {t: v[0] for t, v in page_of.items() if len(v) == 1}
by_name = {}
for slug, x in sages.items():
    for t in set(x["titles_he"]) | {x["he"]}:
        for n in {t, re.sub(r"^(?:רבי|רב|רבן) ", "", t)}:
            by_name.setdefault(n, set()).add(slug)
def match(target):
    s = owner.get(canon.get(target) or target)
    if s: return s
    n = re.sub(r"\s*\(.*?\)", "", canon.get(target) or target).strip()
    if len(n.split()) >= 3 and len(by_name.get(n, ())) == 1: return next(iter(by_name[n]))
    return None
# family word -> what the LINKED person is to the page's sage
WORDS = [("אביו", "father"), ("אביה", "father"), ("בנו של", "father"), ("בנם של", "father"), ("בנו", "child"), ("בתו", "child"), ("בניו", "child"),
         ("נכדו של", "grandparent"), ("נכדו", "grandchild"), ("סבו", "grandparent"), ("חתנו", "son_in_law"), ("חותנו", "in_law"), ("אשתו", "spouse"), ("אחיו", "sibling")]
LINK = r"\[\[([^\]|#]+)(?:\|[^\]]*)?\]\]"
have = {}
for k, x in kit.items():
    L = x.get("links") or {}
    for r, v in L.items():
        for l in v:
            if l.get("id"): have.setdefault(k, set()).add(l["id"]); have.setdefault(l["id"], set()).add(k)
rows = []
for f in sorted(PAGES.glob("*.json")):
    slug = f.stem; d = json.loads(f.read_text(encoding="utf-8")); t = d.get("text") or ""
    m = re.search(r"\n\}\}\n", t); body = t[m.end():] if m else t           # past the infobox
    body = re.sub(r"<ref[^>]*?/>|<ref[^>]*>.*?</ref>", "", body, flags=re.S)
    for word, rel in WORDS:
        for hit in re.finditer(re.escape(word) + r"[^\[\n.]{0,25}?" + LINK, body):
            b = match(hit.group(1).strip())
            if not b or b == slug or b in have.get(slug, set()): continue
            rows.append((slug, rel, b, body[max(0, hit.start() - 30):hit.end() + 40].replace("\n", " ")))
seen = set(); out = ["# Family links in Hebrew Wikipedia's article text that sages.json lacks (candidates, unverified)\n",
                     "Generated by sages_body_audit.py. Check each against the article; accept by adding [slug, relation, slug] to kit_overrides.json add_links (relations: father, children, spouse, in_laws, sons_in_law, siblings, grandparents, grandchildren).\n"]
for slug, rel, b, ctx in rows:
    key = (slug, rel, b)
    if key in seen: continue
    seen.add(key)
    out.append(f"- **{sages[slug]['en']}** ← {rel}: **{sages[b]['en']}**  (`{slug}` / `{b}`)  …{ctx}…")
(OUT / "body_relations_audit.md").write_text("\n".join(out), encoding="utf-8")
print(len(seen), "candidate relations from", len(list(PAGES.glob('*.json'))), "pages ->", OUT / "body_relations_audit.md")
